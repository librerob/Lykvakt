import { createHmac } from "node:crypto";
import { expect, it } from "vitest";
import { codeFor, decodeBase32 } from "../src/otp";
import { parseURI, toURI, verifyBackup } from "../src/import";
import { readImport } from "../src/import-formats";
import { canonical, createEnvelope, snapshot } from "../src/crypto";
import { emptyVault, validateAccount, validateData } from "../src/model";
import { OldFormatError } from "../src/format";
import { fixture } from "./helpers/source-exports.mjs";
const steam = () =>
  parseURI(
    "otpauth://steam/Steam:synthetic-steam?secret=GEZDGNBVGY3TQOJQGEZDGNBVGY3TQOJQ&issuer=Steam&algorithm=SHA1&digits=5&period=30",
  );
// Frozen vectors generated by running ValvePython's published function with Python stdlib HMAC.
const vectors: { seconds: number; code: string }[] = JSON.parse(
  fixture("steam-vectors.json"),
);
it.each(vectors)(
  "Steam published-reference vector at $seconds seconds is $code",
  async ({ seconds, code }) => {
    expect(await codeFor(steam(), seconds * 1000)).toBe(code);
  },
);
it("Steam boundary times also agree with an independent Node/OpenSSL implementation", async () => {
  const account = steam();
  for (const ms of [0, 29999, 30000, 30001, 59999, 60000, 2038000000000]) {
    const counter = Buffer.alloc(8);
    counter.writeBigUInt64BE(BigInt(Math.floor(ms / 30000)));
    const digest = createHmac("sha1", decodeBase32(account.secret))
      .update(counter)
      .digest();
    const truncated = digest.readUInt32BE(digest[19]! & 15) & 0x7fffffff;
    const expected = Array.from(
      { length: 5 },
      (_, i) =>
        "23456789BCDFGHJKMNPQRTVWXY"[Math.floor(truncated / 26 ** i) % 26],
    ).join("");
    expect(await codeFor(account, ms)).toBe(expected);
  }
  expect(await codeFor(account, 29999)).toBe(await codeFor(account, 0));
  expect(await codeFor(account, 30000)).not.toBe(await codeFor(account, 29999));
});
it("maFile Base64 and Aegis Base32 normalize to the same Steam secret and export/import exactly", async () => {
  const ma = (await readImport(fixture("steam.maFile"))).accounts[0]!;
  const aegis = (await readImport(fixture("aegis.json"))).accounts.find(
    (a) => a.type === "steam",
  )!;
  expect(ma.secret).toBe(aegis.secret);
  expect(ma.type).toBe("steam");
  expect(ma.digits).toBe(5);
  expect({ ...parseURI(toURI(ma)), id: ma.id }).toEqual(ma);
});
it.each([
  { digits: 6 },
  { algorithm: "SHA-256" },
  { period: 60 },
  { counter: "1" },
  { secret: "MTIzNDU2Nzg5MDEyMzQ1Njc4OTA=" },
])("Steam schema rejects conflicting settings %j", (change) => {
  expect(() => validateAccount({ ...steam(), ...change })).toThrow();
});
it("Steam survives encrypted backups, account validation, canonicalization and snapshots without relaxing old-format refusal", async () => {
  const data = emptyVault();
  data.accounts.push(steam());
  expect(validateData(data)).toEqual(data);
  expect(canonical(data)).toContain('"type":"steam"');
  const encrypted = await createEnvelope(
    "synthetic Steam backup password",
    data,
    "backup",
  );
  const result = await verifyBackup(
    encrypted.envelope,
    "synthetic Steam backup password",
    data,
  );
  expect(result.matches).toBe(true);
  expect(result.data.accounts).toEqual(data.accounts);
  expect(await snapshot(result.data)).toBe(await snapshot(data));
  for (const version of [1, 2])
    expect(() => validateData({ ...data, version })).toThrow(OldFormatError);
}, 60000);
